const cache = new Map<string, EquipInfo | null>();
let cacheNamesVersion = 0;

/** The gear template behind an item type, or undefined when the type is not equipment. */
export function equipmentInfo(type: string): EquipInfo | undefined {
  if (cacheNamesVersion !== gearNamesVersion()) {
    cache.clear(); // a set was renamed
    cacheNamesVersion = gearNamesVersion();
  }
  const hit = cache.get(type);
  if (hit !== undefined) return hit ?? undefined;
  let info: EquipInfo | null = SPECIAL_EQUIPMENT[type] ?? null;
  if (!info) {
    const m = ID_PATTERN.exec(type);
    if (m) {
      const kind = m[1] as EquipKind;
      const style = m[2] as EquipStyle;
      const realm = Number(m[3]);
      const tier = Number(m[4]);
      const grade = Number(m[5]);
      const element = m[6] ?? null;
      const weaponType = m[7] ?? null;
      const attrOk =
        (element === null || (GEAR_ELEMENTS as readonly string[]).includes(element)) &&
        (weaponType === null || (kind === "weapon" && (WEAPON_TYPES as readonly string[]).includes(weaponType)));
      const kindOk = (EQUIP_KINDS as readonly string[]).includes(kind);
      const styleOk = kindOk && (GENDERED_KINDS.has(kind) ? style !== "u" : style === "u");
      if (kindOk && styleOk && attrOk && realm < REALMS.length && tier >= 1 && tier <= STAGES_PER_REALM && grade >= 1 && grade <= MAX_EQUIP_GRADE) {
        info = buildInfo(kind, style, realm, tier, grade, element, weaponType);
      }
    }
  }
  cache.set(type, info);
  return info ?? undefined;
}

/** Small label for a piece's realm and bậc, e.g. "LK3" for Luyện Khí 3 or "TC4" for Trúc Cơ 4. */
export function equipTierTag(info: { realm: number; tier: number }): string {
  return `${REALMS[info.realm]?.shortVi ?? ""}${info.tier}`;
}

export function isEquipmentType(type: string): boolean {
  return equipmentInfo(type) !== undefined;
}

/** Durability a freshly created piece starts with: both undefined for pieces that never wear out. */
export function newDurability(type: string): { dur: number; max: number } | null {
  const max = equipmentInfo(type)?.maxDurability;
  return max ? { dur: max, max } : null;
}

/**
 * Stats rolled for one piece when it was created (final values, already scaled by its grade), kept with the item: no two pieces of the
 * same kind need have the same stats. Absent on pieces made before rolling existed (they use the fixed stats of their type).
 */
export type RolledStats = Partial<Record<EquipStatKey, number>>;

/** A stored/received value as RolledStats, or undefined when it is not one (unknown keys dropped, numbers sane). */
export function parseRolledStats(raw: unknown): RolledStats | undefined {
  let v = raw;
  if (typeof v === "string") {
    try {
      v = JSON.parse(v);
    } catch {
      return undefined;
    }
  }
  if (typeof v !== "object" || v === null || Array.isArray(v)) return undefined;
  const out: RolledStats = {};
  for (const key of EQUIP_STAT_KEYS) {
    const n = (v as Record<string, unknown>)[key];
    if (typeof n === "number" && Number.isFinite(n) && n >= 0 && n <= 100_000) out[key] = n;
  }
  return Object.keys(out).length > 0 ? out : undefined;
}

/** One worn piece, as the room and the client see it. `dur`/`max` are absent for pieces that never wear out. */
export interface EquippedItem {
  id: string;
  type: string;
  slot: EquipSlot;
  dur?: number;
  max?: number;
  /** Pháp bảo bản mệnh only: its trained level (flat level index) and the EXP towards the next one. Absent: still at its own level, no EXP. */
  lv?: number;
  xp?: number;
  /** Rolled stats of this piece (see RolledStats). */
  rs?: RolledStats;
  /** Upgrade level from the blacksmith (+1..+10); absent: +0. */
  en?: number;
}

/** Level and EXP of the pháp bảo bản mệnh, which has its own EXP stream (half of what a character needs per level, never above the owner's level). */
export function isBonded(type: string): boolean {
  return equipmentInfo(type)?.kind === "bonded";
}

/** The level a bonded artifact is at: its trained level, or the level it was made at. */
export function refineLevelOf(info: EquipInfo, lv: number | undefined): number {
  return lv ?? levelIndex(info.realm, info.tier);
}

/** EXP the artifact needs to go from `level` to the next: half of the character's need at the same level. */
export function refineExpNeeded(level: number): number {
  const realm = Math.floor(level / STAGES_PER_REALM);
  const stage = (level % STAGES_PER_REALM) + 1;
  return Math.max(1, Math.round(expToNext(realm, stage) / 2));
}

/**
 * Adds EXP to a bonded artifact: it levels up as long as the EXP pays for it, but never beyond `cap` (the owner's own level).
 * At the cap the EXP stops at the amount that would be needed (the overflow is dropped), like a character at stage 9.
 */
export function applyRefineExp(level: number, xp: number, gain: number, cap: number): { lv: number; xp: number; levelsGained: number } {
  let lv = level;
  let exp = xp + Math.max(0, Math.floor(gain));
  let gained = 0;
  while (lv < cap) {
    const need = refineExpNeeded(lv);
    if (exp < need) break;
    exp -= need;
    lv += 1;
    gained += 1;
  }
  if (lv >= cap) exp = Math.min(exp, refineExpNeeded(lv));
  return { lv, xp: exp, levelsGained: gained };
}

/** Stats at the current durability: a piece at 60% gives 60% (rounded down) of each stat; a broken one gives nothing. */
export function baseStatsAt(info: EquipInfo, lv: number | undefined, rolled?: RolledStats): EquipStats {
  if (info.kind === "bonded" && lv !== undefined) return formulaStats(info.kind, lv, info.grade);
  // A piece with rolled stats uses them; a stat it did not roll is 0 (the roll covers every stat the kind has).
  return rolled ? { ...emptyEquipStats(), ...rolled } : { ...info.stats };
}

export function scaledStats(info: EquipInfo, dur: number | undefined, max: number | undefined, lv?: number, mult = 1, rolled?: RolledStats, en?: number): EquipStats {
  const base = baseStatsAt(info, lv, rolled);
  const enh = enhanceStatMult(en);
  const noWear = dur === undefined || max === undefined || max <= 0;
  if (noWear && mult === 1 && enh === 1) return base;
  const out = emptyEquipStats();
  const wearF = noWear ? 1 : Math.min(1, Math.max(0, dur / max));
  const f = wearF * mult * enh;
  for (const key of EQUIP_STAT_KEYS) {
    // Speed is not scaled by resonance or the upgrade level (the grade is left out of its roll too), only by wear.
    const v = base[key] * (key === "moveSpeed" ? wearF : f);
    out[key] = EQUIP_RATE_KEYS.includes(key) ? Math.floor(v * 10) / 10 : Math.floor(v);
  }
  return out;
}

export function isBroken(dur: number | undefined): boolean {
  return dur !== undefined && dur <= 0;
}

/**
 * Extra strength of gear that suits its wearer: a piece whose element is the wearer's spiritual root (or an element their
 * constitution favours), or a weapon of a family their constitution favours, gives this much more (0.15 = +15% on all its
 * stats). One number so it is easy to tune; a piece gets it once however many ways it matches.
 */
export const AFFINITY_BONUS = 0.15;

/** The elements and weapon families a character resonates with: their root plus whatever their constitution targets. */
export interface GearAffinity {
  elements: readonly string[];
  weapons: readonly string[];
}

export function gearAffinity(roots: readonly string[], constitutionEffects: readonly ConstitutionEffect[]): GearAffinity {
  const elements = new Set<string>(roots);
  const weapons = new Set<string>();
  for (const e of constitutionEffects) {
    if (e.targetKind === "element") elements.add(e.targetTag);
    else if (e.targetKind === "weapon") weapons.add(e.targetTag);
  }
  return { elements: [...elements], weapons: [...weapons] };
}

/** Whether a piece suits the wearer (see AFFINITY_BONUS). */
export function resonates(info: Pick<EquipInfo, "element" | "weaponType">, affinity: GearAffinity | undefined): boolean {
  if (!affinity) return false;
  return (info.element !== null && affinity.elements.includes(info.element)) || (info.weaponType !== null && affinity.weapons.includes(info.weaponType));
}

/** Extra strength (0.15 = +15%) a piece gives its wearer: more when its element is a mutant one the wearer has. */
export function resonanceBonus(info: Pick<EquipInfo, "element" | "weaponType">, affinity: GearAffinity | undefined): number {
  if (!resonates(info, affinity)) return 0;
  const mutant = info.element !== null && isMutantRoot(info.element) && !!affinity?.elements.includes(info.element);
  return mutant ? elementTuning().mutantGearBonusPct / 100 : AFFINITY_BONUS;
}

/** What a wearer must satisfy. Requirements are judged against the character without gear. */
export interface WearerCtx {
  /** What the wearer resonates with; leave out when only the requirements are being checked. */
  affinity?: GearAffinity;
  gender: Gender;
  realm: number;
  stage: number;
  base: BaseStats;
  /** Riding the flight pháp bảo. Its stats only count while this is true; every other piece counts either way. */
  mounted?: boolean;
}

export type EquipBlock = "slot" | "gender" | "level" | "stat" | "broken";

/** Why a piece cannot be worn in `slot` (null when it can). Pass `slot` undefined to skip the slot check. */
export function equipBlock(info: EquipInfo, slot: EquipSlot | undefined, dur: number | undefined, w: WearerCtx): EquipBlock | null {
  if (slot !== undefined && !KIND_SLOTS[info.kind].includes(slot)) return "slot";
  if (isBroken(dur)) return "broken";
  if (GENDERED_KINDS.has(info.kind) && info.style !== (gearStyleOf(w.gender) === "male" ? "m" : "f")) return "gender";
  if (info.req.level !== null && levelIndex(w.realm, w.stage) < info.req.level) return "level";
  if (info.req.stat && w.base[info.req.stat.key] < info.req.stat.value) return "stat";
  return null;
}

/** Sum of the stats of every worn piece that is still allowed to count. */
export function equipmentBonus(items: readonly EquippedItem[], w: WearerCtx): EquipStats {
  const total = emptyEquipStats();
  for (const it of items) {
    const info = equipmentInfo(it.type);
    if (!info || equipBlock(info, it.slot, it.dur, w)) continue;
    if (info.kind === "flight" && !w.mounted) continue;
    const s = scaledStats(info, it.dur, it.max, it.lv, 1 + resonanceBonus(info, w.affinity), it.rs, it.en);
    for (const key of EQUIP_STAT_KEYS) total[key] += s[key];
  }
  for (const key of EQUIP_STAT_KEYS) total[key] = Math.round(total[key] * 10) / 10;
  return total;
}

/** Worn pieces that must come off: broken, or the wearer no longer meets their requirements. */
export function mustUnequip(items: readonly EquippedItem[], w: WearerCtx): Array<{ item: EquippedItem; reason: EquipBlock }> {
  const out: Array<{ item: EquippedItem; reason: EquipBlock }> = [];
  for (const it of items) {
    const info = equipmentInfo(it.type);
    if (!info) continue;
    const reason = equipBlock(info, it.slot, it.dur, w);
    if (reason) out.push({ item: it, reason });
  }
  return out;
}

/** Durability a worn piece loses at death, or 0 for a piece that never wears out. */
export function deathDurabilityLoss(max: number | undefined, fraction = DEATH_DURABILITY_FRACTION): number {
  return max === undefined ? 0 : Math.max(1, Math.ceil(max * fraction));
}

/** Linh Thạch to restore `lost` durability points of a piece of the given grade. */
export function repairCost(grade: number, lost: number): number {
  const per = REPAIR_COST_PER_POINT[Math.min(Math.max(grade, 1), REPAIR_COST_PER_POINT.length) - 1] ?? 1;
  return Math.max(0, Math.trunc(lost)) * per;
}

/** Chance (0..1) that a kill drops one piece of gear, and the weights over grades 1..4 for what drops. */
export const EQUIP_DROP: Readonly<Record<MonsterRank, { chance: number; grades: readonly [number, number, number, number]; overLevel: number }>> = {
  normal: { chance: 0.03, grades: [70, 25, 5, 0], overLevel: 0 },
  rare1: { chance: 0.15, grades: [45, 35, 17, 3], overLevel: 0.1 },
  rare2: { chance: 0.3, grades: [25, 35, 30, 10], overLevel: 0.25 },
};

export interface EquipDrop {
  type: string;
  dur?: number;
  max?: number;
}

/**
 * Gear dropped by one kill, or null. Normally the gear belongs to the map's realm and a bậc at or just below the
 * monster's; rare monsters may instead drop over-level gear (the next realm). Uses exactly nine rolls so the order of
 * a seeded sequence stays stable: chance, kind, style, bậc, grade, over-level, over-level bậc, element, weapon type.
 */
export function rollEquipmentDrop(mapRealm: number, monsterTier: number, rank: MonsterRank, rand: () => number, chanceMult = 1): EquipDrop | null {
  const cfg = EQUIP_DROP[rank];
  const chance = rand();
  const kindRoll = rand();
  const styleRoll = rand();
  const tierRoll = rand();
  const gradeRoll = rand();
  const overRoll = rand();
  const overTierRoll = rand();
  const elementRoll = rand();
  const weaponRoll = rand();
  if (chance >= cfg.chance * chanceMult) return null;
  const kind = EQUIP_KINDS[Math.floor(kindRoll * EQUIP_KINDS.length)] as EquipKind;
  const style: EquipStyle = GENDERED_KINDS.has(kind) ? (styleRoll < 0.5 ? "m" : "f") : "u";
  let realm = mapRealm;
  let tier = Math.max(1, monsterTier - Math.floor(tierRoll * 3));
  if (overRoll < cfg.overLevel && mapRealm + 1 < REALMS.length) {
    realm = mapRealm + 1;
    tier = 1 + Math.floor(overTierRoll * 3);
  }
  tier = Math.min(STAGES_PER_REALM, tier);
  const total = cfg.grades.reduce((s, w) => s + w, 0);
  let acc = 0;
  let grade = 1;
  for (let g = 0; g < cfg.grades.length; g++) {
    acc += cfg.grades[g]!;
    if (gradeRoll * total < acc) {
      grade = g + 1;
      break;
    }
  }
  // A small share of drops carry a mutant element; the same roll decides, so the number of rolls stays nine.
  const mutantChance = elementTuning().mutantGearDropPermille / 1000;
  const element =
    elementRoll < mutantChance
      ? (MUTANT_ROOTS[Math.min(MUTANT_ROOTS.length - 1, Math.floor((elementRoll / mutantChance) * MUTANT_ROOTS.length))] as string)
      : (DROP_ELEMENTS[Math.floor(((elementRoll - mutantChance) / (1 - mutantChance)) * DROP_ELEMENTS.length)] as string);
  const weaponType = kind === "weapon" ? (WEAPON_TYPES[Math.floor(weaponRoll * WEAPON_TYPES.length)] as string) : undefined;
  const type = makeEquipmentId(kind, style, realm, tier, grade, element, weaponType);
  const d = newDurability(type);
  return d ? { type, dur: d.dur, max: d.max } : { type };
}
